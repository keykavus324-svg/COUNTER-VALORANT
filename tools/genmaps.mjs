/**
 * Map baker.
 *
 * The radars give us a walkable mask; gridLayout.js turns that mask into
 * collision boxes, a waypoint graph and tactical spots. Doing that at load time
 * costs ~600 ms per map on a laptop, which is the single slowest thing about
 * changing arenas. This tool bakes the result into plain data modules so the
 * browser only has to parse arrays.
 *
 *   node tools/genmaps.mjs
 *
 * Emits src/data/maps/<id>.js:
 *   WALLS  [x, z, w, d, h, kind]
 *   NODES  [x, z, tagIndex]
 *   EDGES  adjacency list, one line per node
 *   SPOTS  plant / hold / attack path data
 *   META   bounds, spawns, sites, radar mapping
 */
import fs from 'node:fs';
import path from 'node:path';
import { MAPS } from '../src/world/mapLayout.js';
import { decodeMask, buildWalls, buildNav, buildSpots } from '../src/world/gridLayout.js';

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'src', 'data', 'maps');
fs.mkdirSync(OUT, { recursive: true });

const r2 = (v) => Math.round(v * 100) / 100;
const round = (v, p = 3) => Number(v.toFixed(p));
const TAG_INDEX = { map: 0, A: 1, B: 2, mid: 3, spawn: 4 };

let totalLines = 0;
const summary = [];

for (const map of MAPS) {
  const cells = decodeMask(map);
  const walls = buildWalls(map, cells);
  const nav = buildNav(map, cells);
  const spots = buildSpots(map, cells, nav.nodes, nav.edges);

  const lines = [];
  const p = (t = '') => lines.push(t);

  p('/**');
  p(` * Baked layout for ${map.name} — GENERATED by tools/genmaps.mjs, do not edit.`);
  p(' *');
  p(` * ${nav.nodes.length} waypoints · ${walls.length} collision boxes · ${cells.length} mask cells.`);
  p(' * Regenerate with: npm run genmaps');
  p(' */');
  p('');
  p(`export const ID = '${map.id}';`);
  p(`export const META = {`);
  p(`  id: '${map.id}',`);
  p(`  name: ${JSON.stringify(map.name)},`);
  p(`  theme: ${JSON.stringify(map.theme || 'sand')},`);
  p(`  desc: ${JSON.stringify(map.desc || '')},`);
  p(`  radar: ${JSON.stringify(map.radar || '')},`);
  p(`  bounds: { minX: ${r2(map.bounds.minX)}, maxX: ${r2(map.bounds.maxX)}, minZ: ${r2(map.bounds.minZ)}, maxZ: ${r2(map.bounds.maxZ)} },`);
  p(`  cell: ${map.cell},`);
  p(`  meta: { pos: [${(map.meta?.pos || [0, 0]).join(', ')}], scale: ${map.meta?.scale ?? 1}, size: ${map.meta?.size ?? 1024} },`);
  p(`  sites: {`);
  for (const key of ['A', 'B']) {
    const s = map.sites[key];
    p(`    ${key}: { center: { x: ${r2(s.center.x)}, z: ${r2(s.center.z)} }, radius: ${r2(s.radius)} },`);
  }
  p('  },');
  p('  spawns: {');
  p(`    attacker: [${map.spawns.attacker.map((s) => `{ x: ${r2(s.x)}, z: ${r2(s.z)} }`).join(', ')}],`);
  p(`    defender: [${map.spawns.defender.map((s) => `{ x: ${r2(s.x)}, z: ${r2(s.z)} }`).join(', ')}],`);
  p('  },');
  p('};');
  p('');

  // ---------------- collision ----------------
  p('/** [x, z, width, depth, height, kind] */');
  p('export const WALLS = [');
  for (const w of walls) {
    p(`  [${r2(w[0])}, ${r2(w[1])}, ${r2(w[2])}, ${r2(w[3])}, ${r2(w[4])}, '${w[5] || 'concrete'}'],`);
  }
  p('];');
  p('');

  // ---------------- waypoints ----------------
  p('/** [x, z, tagIndex] — tag 0 map, 1 A, 2 B, 3 mid, 4 spawn */');
  p('export const NODES = [');
  for (const n of nav.nodes) {
    p(`  [${r2(n.x)}, ${r2(n.z)}, ${TAG_INDEX[n.tag] ?? 0}],`);
  }
  p('];');
  p('');

  // ---------------- adjacency ----------------
  p('/** Adjacency list, one line per waypoint: [neighbourIndex, ...] */');
  p('export const EDGES = [');
  for (const list of nav.edges) {
    const ids = list.map((e) => e.to).join(', ');
    p(`  [${ids}],`);
  }
  p('];');
  p('');

  // ---------------- per waypoint cover / exposure scores ----------------
  const inBounds = (c, r) => c >= 0 && r >= 0 && c < map.cols && r < map.rows;
  const solid = (c, r) => (inBounds(c, r) ? cells[r * map.cols + c] === 0 : true);
  const cellOf = (n) => [Math.round((n.x - map.origin.x) / map.cell), Math.round((map.origin.z - n.z) / map.cell)];
  p('/** [cover, peek] per waypoint — how much of the spot is shielded vs exposed. */');
  p('export const NODE_SCORES = [');
  for (const n of nav.nodes) {
    const [c, r] = cellOf(n);
    let blocked = 0;
    let open = 0;
    for (let dr = -3; dr <= 3; dr++) {
      for (let dc = -3; dc <= 3; dc++) {
        if (!dc && !dr) continue;
        const d = Math.hypot(dc, dr);
        if (d > 3.2) continue;
        if (solid(c + dc, r + dr)) blocked++;
        else open++;
      }
    }
    const cover = blocked / Math.max(1, blocked + open);
    const peek = open / Math.max(1, blocked + open);
    // a good spot is shielded but still has sightlines: reward the balance
    p(`  [${round(cover)}, ${round(peek)}, ${round(cover * 0.6 + peek * 0.4)}],`);
  }
  p('];');
  p('');

  // ---------------- cover props ----------------
  p('/** [x, z, w, d, h, kind] deterministic cover crates near sites. */');
  p('export const PROPS = [');
  const propSeeds = nav.nodes.filter((n, i) => i % 41 === 0);
  for (const n of propSeeds) {
    // only drop a crate in genuinely open space so it can never seal a corridor
    const [c, r] = cellOf(n);
    let openNeighbours = 0;
    for (let dr = -2; dr <= 2; dr++) {
      for (let dc = -2; dc <= 2; dc++) {
        if (!dc && !dr) continue;
        if (!solid(c + dc, r + dr)) openNeighbours++;
      }
    }
    if (openNeighbours < 21) continue;
    p(`  [${round(n.x + 1.5)}, ${round(n.z - 1.1)}, 1.1, 1.1, 1.15, 'crate'],`);
  }
  p('];');
  p('');

  // ---------------- tactical spots ----------------
  const plantA = spots.plantSpots?.A || [];
  const plantB = spots.plantSpots?.B || [];
  p('export const SPOTS = {');
  p('  plant: {');
  p(`    A: [${plantA.map((s) => `{ x: ${r2(s.x)}, z: ${r2(s.z)} }`).join(', ')}],`);
  p(`    B: [${plantB.map((s) => `{ x: ${r2(s.x)}, z: ${r2(s.z)} }`).join(', ')}],`);
  p('  },');
  p('  hold: {');
  for (const key of ['A', 'B', 'mid']) {
    const list = spots.holdSpots?.[key] || [];
    p(`    ${key}: [`);
    for (const s of list) {
      p(`      { x: ${r2(s.x)}, z: ${r2(s.z)}, look: { x: ${r2(s.look?.x ?? 0)}, z: ${r2(s.look?.z ?? 0)} } },`);
    }
    p('    ],');
  }
  p('  },');
  p('  paths: {');
  for (const key of ['A', 'B']) {
    p(`    ${key}: {`);
    const routes = spots.attackPaths?.[key] || {};
    for (const [lane, pts] of Object.entries(routes)) {
      p(`      ${lane}: [${(pts || []).map((q) => `[${r2(q[0] ?? q.x)}, ${r2(q[1] ?? q.z)}]`).join(', ')}],`);
    }
    p('    },');
  }
  p('  },');
  p('};');
  p('');
  p('export default { ID, META, WALLS, NODES, EDGES, NODE_SCORES, PROPS, SPOTS };');

  const text = lines.join('\n');
  fs.writeFileSync(path.join(OUT, `${map.id}.js`), text);
  const n = lines.length;
  totalLines += n;
  summary.push(`${map.id.padEnd(12)} ${String(n).padStart(6)} satır  (${nav.nodes.length} waypoint, ${walls.length} kutu)`);
}

const ids = MAPS.map((m) => m.id);
const index = [
  '/**',
  ' * Baked map registry — GENERATED by tools/genmaps.mjs.',
  ' *',
  ' * Every arena is a dynamic import: the shell and the main menu never wait for',
  ' * megabytes of waypoint data, and a weak machine only downloads the map it',
  ' * actually plays.',
  ' */',
  'const cache = new Map();',
  '',
  'const LOADERS = {',
  ...ids.map((id) => `  ${id}: () => import('./${id}.js'),`),
  '};',
  '',
  'export const BAKED_IDS = Object.keys(LOADERS);',
  '',
  '/** Synchronously available baked map, or null when it is not loaded yet. */',
  'export function bakedMap(id) {',
  '  return cache.get(id) || null;',
  '}',
  '',
  '/** Load (and cache) a baked map; resolves to the module namespace. */',
  'export async function loadBakedMap(id) {',
  '  if (cache.has(id)) return cache.get(id);',
  '  const loader = LOADERS[id];',
  '  if (!loader) return null;',
  '  const mod = await loader();',
  '  cache.set(id, mod);',
  '  return mod;',
  '}',
  '',
  '/** Fire and forget preload (used when the menu shows a map). */',
  'export function preloadBakedMap(id) {',
  '  if (!cache.has(id)) loadBakedMap(id).catch(() => {});',
  '}',
  '',
  'export const BAKED_MAPS = { get: bakedMap };',
  '',
].join('\n');
fs.writeFileSync(path.join(OUT, 'index.js'), index);

console.log(summary.join('\n'));
console.log(`\ntoplam: ${totalLines} satır + index`);
